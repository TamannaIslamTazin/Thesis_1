/**
 * Safely parse data with a Zod schema, returning a typed result.
 * Throws ZodError on validation failure.
 */
export function validateOrThrow<T>(schema: z.ZodSchema<T>, data: unknown): T {
  return schema.parse(data);
}

/**
 * Safely parse data with a Zod schema, returning a result object.
 * Does not throw - returns { success: false, error } on failure.
 */
export function validateSafe<T>(schema: z.ZodSchema<T>, data: unknown): z.SafeParseReturnType<unknown, T> {
  return schema.safeParse(data);
}

/**
 * Validate a DID string and return the method.
 * Returns null if invalid.
 */
export function extractDIDMethod(did: string): string | null {
  const result = DIDSchema.safeParse(did);
  if (!result.success) return null;
  
  const match = did.match(/^did:([^:]+):/);
  return match ? match[1] : null;
}

/**
 * Check if a credential is expired.
 *
 * Reads the VC 2.0 `validUntil` first and falls back to the VC 1.1
 * `expirationDate`. Reading only `expirationDate` — as this did before the VC
 * 2.0 migration — made every expired v2 credential report as unexpired, because
 * v2 does not carry that member at all.
 */
export function isCredentialExpired(
  credential: Pick<
    z.infer<typeof VerifiableCredentialSchema>,
    'expirationDate' | 'validUntil'
  >,
): boolean {
  const expiry = credential.validUntil ?? credential.expirationDate;
  if (!expiry) return false;
  return new Date(expiry) < new Date();
}

/**
 * Format Zod errors into a user-friendly message.
 */
export function formatZodError(error: z.ZodError): string {
  return error.errors
    .map((e) => `${e.path.join('.')}: ${e.message}`)
    .join('; ');
}

/**
 * Create a validation middleware for Express routes.
 * Returns a function that validates request body against a schema.
 */
export function createBodyValidator<T>(schema: z.ZodSchema<T>) {
  return (body: unknown): { success: true; data: T } | { success: false; error: string } => {
    const result = schema.safeParse(body);
    if (result.success) {
      return { success: true, data: result.data };
    }
    return { success: false, error: formatZodError(result.error) };
  };
}

/**
 * Validate query parameters with pagination defaults.
 */
export function validatePagination(query: unknown): PaginationParams {
  return PaginationSchema.parse(query);
}
