// ---------------------------------------------------------------------------
// Database Identifier Validation
// ---------------------------------------------------------------------------

/**
 * Validation for Prisma primary keys declared as `@id @default(cuid())`.
 *
 * Every model in prisma/schema.prisma uses cuid, NOT uuid. Validating one of
 * these identifiers with `z.string().uuid()` rejects every real ID and makes
 * the endpoint permanently unreachable — that is exactly how the consent and
 * emergency-access revocation endpoints came to be dead on arrival.
 *
 * Accepts both cuid v1 (`c` + 24 base36 chars) and cuid2 (leading letter plus
 * lowercase alphanumerics), and rejects uuids, empty strings, and anything
 * carrying separators or punctuation.
 *
 * Do NOT use this for values generated by `uuidv4()` — presentation
 * `requestId` and OID4VCI `preAuthorizedCode` are genuine uuids and must keep
 * using `z.string().uuid()`.
 */
export const CuidSchema = z.string()
  .regex(
    /^[a-z][a-z0-9]{6,31}$/,
    'Invalid identifier format (expected a cuid)'
  );

// ---------------------------------------------------------------------------
// DID Validation
// ---------------------------------------------------------------------------

/**
 * DID format validation with proper structure checking.
 * Supports did:cheqd, did:key, did:web methods.
 * 
 * DID format: did:<method>:<method-specific-id>
 * Examples:
 *   - did:cheqd:bdhealthtestnet:abc123
 *   - did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK
 *   - did:web:example.com
 */
export const DIDSchema = z.string()
  .min(7, 'DID must be at least 7 characters')
  .max(512, 'DID must not exceed 512 characters')
  .regex(
    /^did:(cheqd|key|web|ion|ethr|pkh|ens|jwk|peer):[a-zA-Z0-9._:%-]+$/,
    'Invalid DID format. Must be did:<method>:<method-specific-id>'
  );

/**
 * did:key specific validation - ensures proper multibase encoding.
 * did:key DIDs use z (base58btc) prefix for Ed25519 keys.
 */
export const DIDKeySchema = z.string()
  .regex(
    /^did:key:z[1-9A-HJ-NP-Za-km-z]+$/,
    'Invalid did:key format. Must start with did:key:z followed by base58btc encoded key'
  );

/**
 * did:cheqd specific validation.
 * Format: did:cheqd:<network>:<unique-id>
 *
 * The network segment names OUR sovereign chains, not cheqd's public ones.
 * `mainnet` and `testnet` are rejected deliberately: they identify chains we
 * do not control, and a DID carrying one of them cannot resolve on our ledger.
 * This mirrors the alternation in @credo-ts/cheqd's `parseCheqdDid` and the
 * `did_namespace` the node enforces — all three must agree or DIDs become
 * creatable-but-unresolvable, or the reverse.
 */
export const DIDCheqdSchema = z.string()
  .regex(
    /^did:cheqd:(bdhealthtestnet|bdhealth):[a-zA-Z0-9-]+$/,
    'Invalid did:cheqd format. Must be did:cheqd:(bdhealthtestnet|bdhealth):<unique-id>'
  );

