/**
 * The wallet credential envelope returned by `GET /api/users/me/credentials`
 * and `GET /api/users/me/credentials/:id`.
 *
 * See the `WalletCredential` interface in `../types` for why the envelope
 * exists and why these specific fields are in it. This schema is the runtime
 * half of that contract: the SDK validates responses against it at the network
 * boundary, because a TypeScript `as` cast on a `fetch` result proves nothing
 * and previously let an `undefined` issuer reach a `.id` dereference.
 *
 * `id` uses `CuidSchema` — it is the Prisma row id, not the VC id.
 */
export const WalletCredentialSchema = z.object({
  id: CuidSchema,
  holderDid: DIDSchema,
  issuerDid: DIDSchema,
  type: z.array(z.string().min(1).max(256)).min(1),
  category: WalletCredentialCategorySchema,
  name: z.string().min(1).max(256),
  description: z.string().max(2000).optional(),
  credentialHash: z.string().min(1).max(256),
  status: WalletCredentialStatusSchema,
  issuedAt: z.string().datetime({ offset: true }),
  expiresAt: z.string().datetime({ offset: true }).optional(),
  revokedAt: z.string().datetime({ offset: true }).optional(),
  revocationReason: z.string().max(1000).optional(),
  lastUsedAt: z.string().datetime({ offset: true }).optional(),
  useCount: z.number().int().min(0),
  createdAt: z.string().datetime({ offset: true }),
  updatedAt: z.string().datetime({ offset: true }),
  credential: StoredVerifiableCredentialSchema,
  // The enveloping proof (VC 2.0) — the compact JWT or SD-JWT that actually
  // carries the issuer's signature. Optional: Data Integrity proofs have no
  // envelope. The ceiling is generous because an SD-JWT carries one disclosure
  // per selectively-disclosable claim and so is materially larger than the
  // plain JWT for the same credential.
  credentialJwt: z.string().min(1).max(131072).optional(),
  // Which securing mechanism the envelope above uses. Explicit rather than
  // sniffed — see the `credentialFormat` docstring on `WalletCredential`.
  credentialFormat: z.enum(['vc+jwt', 'vc+sd-jwt', 'jwt_vc_json', 'ldp_vc']).optional(),
});

