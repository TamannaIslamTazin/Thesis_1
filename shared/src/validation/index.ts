// ---------------------------------------------------------------------------
// Data model / date-naming cross-check
// ---------------------------------------------------------------------------

const W3C_CREDENTIALS_V1_CONTEXT = 'https://www.w3.org/2018/credentials/v1';
const W3C_CREDENTIALS_V2_CONTEXT = 'https://www.w3.org/ns/credentials/v2';

/**
 * Reject a credential that declares one data model and dates itself in the
 * other's vocabulary.
 *
 * WHY A CROSS-CHECK IS NEEDED AND FIELD-LEVEL RULES ARE NOT ENOUGH.
 *
 * Both naming pairs have to be individually optional, because exactly one pair
 * is present on any given credential and the schemas must accept both models.
 * The cost of that necessary looseness is that a VC 2.0 `@context` paired with
 * a VC 1.1 `issuanceDate` validated cleanly — a credential that is v2 by
 * declaration and v1 by content.
 *
 * That combination is not a harmless style difference. `credentialValidFrom()`
 * falls back across both names and would happily read it, but Credo's v2 stack
 * does not: it reads `validFrom` only, so such a credential has NO validity
 * start as far as the verifier is concerned. Left unchecked, the two data
 * models blend into a third that nothing implements consistently.
 *
 * Deliberately silent when the context names neither model or both: this rule
 * exists to catch mixing, not to police context lists it does not understand.
 */
function checkDataModelDateNaming(
  credential: {
    '@context'?: unknown;
    issuanceDate?: unknown;
    expirationDate?: unknown;
    validFrom?: unknown;
    validUntil?: unknown;
  },
  ctx: z.RefinementCtx,
): void {
  const contexts = Array.isArray(credential['@context'])
    ? credential['@context'].filter((entry): entry is string => typeof entry === 'string')
    : [];

  const declaresV1 = contexts.includes(W3C_CREDENTIALS_V1_CONTEXT);
  const declaresV2 = contexts.includes(W3C_CREDENTIALS_V2_CONTEXT);

  // Neither or both — nothing unambiguous to enforce.
  if (declaresV1 === declaresV2) return;

  if (declaresV2) {
    for (const field of ['issuanceDate', 'expirationDate'] as const) {
      if (credential[field] !== undefined) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: [field],
          message:
            `'${field}' is VC 1.1 naming but '@context' declares VC 2.0. ` +
            `Use '${field === 'issuanceDate' ? 'validFrom' : 'validUntil'}' instead.`,
        });
      }
    }
    return;
  }

  for (const field of ['validFrom', 'validUntil'] as const) {
    if (credential[field] !== undefined) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: [field],
        message:
          `'${field}' is VC 2.0 naming but '@context' declares VC 1.1. ` +
          `Use '${field === 'validFrom' ? 'issuanceDate' : 'expirationDate'}' instead.`,
      });
    }
  }
}

