/**
 * Proof shape accepted on a stored credential.
 *
 * `ProofSchema` above models a Data Integrity proof and requires `created`,
 * `verificationMethod`, `proofPurpose` and `proofValue`. Every credential this
 * system issues is signed as `jwt_vc` (see `credentialService.issueCredential`
 * and the OID4VCI issuance path), whose proof is `{ type: 'JwtProof2020',
 * jwt: '<compact jwt>' }` — it has none of those four fields. Validating a real
 * credential against `ProofSchema` therefore fails 100% of the time, which is
 * exactly the class of "strict schema nobody ran against real data" bug that
 * makes an endpoint dead on arrival.
 *
 * This schema accepts either family and requires only `type`.
 */
export const StoredProofSchema = z.object({
  type: z.string().min(1).max(128),
  created: z.string().optional(),
  verificationMethod: z.string().max(512).optional(),
  proofPurpose: z.string().max(64).optional(),
  proofValue: z.string().max(8192).optional(),
  jws: z.string().max(8192).optional(),
  jwt: z.string().max(16384).optional(),
}).passthrough();

/**
 * The signed W3C VC as it is actually stored and returned.
 *
 * Deliberately looser than `VerifiableCredentialSchema`:
 *   - `issuanceDate` is validated as a non-empty string, not
 *     `z.string().datetime({ offset: true })`. Credo emits `w3cDate()` values
 *     which are valid ISO 8601 but the exact grammar is Credo's, not ours, and
 *     a client has no business rejecting an issuer's credential over date
 *     punctuation.
 *   - `id` is optional. The JWT-VC encoding moves `vc.id` to the `jti` claim,
 *     so a decoded credential may legitimately arrive without one.
 *   - unknown members pass through. A verifier extension we do not model must
 *     not cause a holder's wallet to drop the credential.
 *
 * What it does enforce is the part clients dereference: `@context`, `type`,
 * `issuer`, and above all `credentialSubject` — the field whose absence made
 * the mobile transform throw and the OID4VP share sheet render zero rows.
 */
export const StoredVerifiableCredentialSchema = z.object({
  '@context': z.array(z.union([z.string(), z.record(z.unknown())])).min(1),
  id: z.string().min(1).max(512).optional(),
  type: z.array(z.string()).min(1).refine(
    (types) => types.includes('VerifiableCredential'),
    'Type must include VerifiableCredential'
  ),
  issuer: z.union([
    z.string().min(1).max(512),
    z.object({ id: z.string().min(1).max(512) }).passthrough(),
  ]),
  // VC 1.1 names the validity window issuanceDate/expirationDate; VC 2.0 names
  // it validFrom/validUntil. Both pairs are optional and the refinement below
  // requires one of the two start fields — requiring `issuanceDate` outright
  // rejected 100% of VC 2.0 credentials at the SDK boundary, which is where a
  // wallet would have silently dropped every credential it was issued.
  issuanceDate: z.string().min(1).max(64).optional(),
  expirationDate: z.string().min(1).max(64).optional(),
  validFrom: z.string().min(1).max(64).optional(),
  validUntil: z.string().min(1).max(64).optional(),
  credentialSubject: CredentialSubjectSchema,
  credentialStatus: z.record(z.unknown()).optional(),
  proof: StoredProofSchema.optional(),
}).passthrough().refine(
  (cred) => Boolean(cred.validFrom ?? cred.issuanceDate),
  "Credential must carry a validity start: 'validFrom' (VC 2.0) or 'issuanceDate' (VC 1.1)",
).superRefine(checkDataModelDateNaming);

