export const VerifiableCredentialSchema = z.object({
  '@context': z.array(z.string()).min(1).refine(
    (ctx) => ctx.includes('https://www.w3.org/2018/credentials/v1') || 
             ctx.includes('https://www.w3.org/ns/credentials/v2'),
    'Context must include W3C Verifiable Credentials context'
  ),
  id: z.string().min(1).max(512),
  type: z.array(z.string()).min(1).refine(
    (types) => types.includes('VerifiableCredential'),
    'Type must include VerifiableCredential'
  ),
  issuer: z.union([
    DIDSchema,
    z.object({
      id: DIDSchema,
      name: z.string().max(256).optional(),
    }),
  ]),
  // See StoredVerifiableCredentialSchema for why both naming pairs are accepted:
  // VC 1.1 uses issuanceDate/expirationDate, VC 2.0 uses validFrom/validUntil.
  issuanceDate: z.string().datetime({ offset: true }).optional(),
  expirationDate: z.string().datetime({ offset: true }).optional(),
  validFrom: z.string().datetime({ offset: true }).optional(),
  validUntil: z.string().datetime({ offset: true }).optional(),
  credentialSubject: CredentialSubjectSchema,
  credentialStatus: CredentialStatusSchema.optional(),
  proof: ProofSchema.optional(),
}).refine(
  (cred) => Boolean(cred.validFrom ?? cred.issuanceDate),
  "Credential must carry a validity start: 'validFrom' (VC 2.0) or 'issuanceDate' (VC 1.1)",
).superRefine(checkDataModelDateNaming);

